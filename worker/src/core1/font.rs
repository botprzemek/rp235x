#[inline]
pub fn get_ibm_pixel(digit: u8, pixel_x: u32, pixel_y: u32) -> bool {
    if digit > 9 || pixel_x >= 7 || pixel_y >= 9 {
        return false;
    }

    let row_data = IBM_FONT_7X9[digit as usize][pixel_y as usize];

    (row_data & (1 << (7 - pixel_x))) != 0
}
